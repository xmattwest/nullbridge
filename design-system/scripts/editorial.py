"""Explicit editorial web context and its portable consumer artifacts.

Default Dawn State colors and data roles are not rethemed. No research workspace
or model is needed to rebuild the illustration or the web tokens.
"""
import hashlib
import html
import json
import math
from pathlib import Path
import re

import figures

SOURCE = Path(__file__).resolve().parents[1] / "profiles/dawn-state/signal-loom.json"


def roles(profile):
    context = profile["webContexts"]["editorial"]
    colors = {**profile["colors"], **context["colors"]}
    names = {**profile["roles"], **context["roles"]}
    return {role: colors[name] for role, name in names.items()}


def contrast_pairs(profile):
    colors = roles(profile)
    return [{"foreground": fg, "background": bg,
             "ratio": round(figures.contrast(colors[fg], colors[bg]), 4)}
            for bg in ("canvas", "surface")
            for fg in ("text-primary", "text-secondary", "kicker", "link", "focus",
                       "personal-text", "personal-muted")] + [
        {"foreground": "on-ui-active", "background": "ui-active",
         "ratio": round(figures.contrast(colors["on-ui-active"], colors["ui-active"]), 4)}]


def validate(profile):
    context = profile["webContexts"]["editorial"]
    assert all(re.fullmatch(r"#[0-9A-F]{6}", value) for value in context["colors"].values())
    assert set(context["roles"].values()) <= set(profile["colors"]) | set(context["colors"])
    assert all(figures.contrast(roles(profile)[p["foreground"]], roles(profile)[p["background"]]) >=
               profile["contract"]["textContrast"] for p in contrast_pairs(profile))
    assert context["publication"]["sizePx"] > 0
    assert context["publication"]["lineHeight"] >= 1
    assert profile["typography"]["publication"]["opticalSizing"] in {"auto", "none"}


def tokens_css(profile):
    context = profile["webContexts"]["editorial"]
    values = roles(profile)
    for role in ("publication", "personal", "heading", "body", "kicker", "code"):
        t = profile["typography"][role]
        values[f"font-{role}"] = figures.font_stack(t)
        values[f"weight-{role}"] = t["weight"]
        values[f"tracking-{role}"] = f'{t["tracking"]}em'
        if "opticalSizing" in t:
            values[f"optical-{role}"] = t["opticalSizing"]
    values["publication-size"] = f'{context["publication"]["sizePx"] / 16:g}rem'
    values["publication-line-height"] = context["publication"]["lineHeight"]
    values["surface-shadow"] = context["surfaces"]["shadow"]
    for key in ("small", "container"):
        values[f"radius-{key}"] = f'{profile["radius"][key]}px'
    return ("/* Generated by Warm Precision build.py from Dawn State's editorial web context. */\n:root {\n" +
            "".join(f"  --wp-{k}: {v};\n" for k, v in values.items()) + "}\n")


def report_tokens_css(profile):
    return ("/* Generated from Dawn State's editorial web context. Frozen figure colors are independent. */\n" +
            "body.lfm3-report {\n" + "".join(f"  --r-{k}: {v};\n" for k, v in roles(profile).items()) + "}\n")


def loom(profile):
    source = json.loads(SOURCE.read_text())
    layers, g = source["layers"], source["geometry"]
    assert len(layers) == 24 and {c: layers.count(c) for c in "CSG"} == {"C": 13, "S": 5, "G": 6}
    colors = roles(profile)
    points = [(g["centerX"] + g["amplitude"] * math.sin(i * 2 * math.pi / g["period"]),
               g["startY"] + i * g["pitch"]) for i in range(len(layers))]
    twin = [(2 * g["centerX"] - x, y) for x, y in points]
    desc = ('A braided emblem with one marked node per backbone layer in released order: ' + ', '.join(layers) +
            '. Green filled nodes: 13 convolutions; slate outlined nodes: five sliding-attention layers; '
            'orange nodes: six global-attention layers. ' + source["interpretation"])
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{g["viewBox"]}" role="img" aria-labelledby="signal-loom-title signal-loom-desc">'
           f'<title id="signal-loom-title">Signal loom</title><desc id="signal-loom-desc">{html.escape(desc)}</desc>']
    slate, green = colors["structure"], colors["ui-active"]
    for strand in (points, twin):
        path = ' '.join(f'{"M" if i == 0 else "L"}{x:.2f},{y:.2f}' for i, (x, y) in enumerate(strand))
        out.append(f'<path d="{path}" fill="none" stroke="{slate}" stroke-width="2" opacity=".6"/>')
    names = {'C': 'short convolution', 'S': 'sliding attention', 'G': 'global attention'}
    fills = {'C': green, 'S': colors["surface"], 'G': colors["emphasis"]}
    for i, ((x, y), (tx, ty), kind) in enumerate(zip(points, twin, layers)):
        out.append(f'<g data-operator="{kind}" data-layer="{i}"><title>Layer {i}: {names[kind]}</title>'
                   f'<path d="M{x:.2f},{y:.2f} L{tx:.2f},{ty:.2f}" stroke="{slate}" stroke-width="1" opacity=".3"/>'
                   f'<rect x="{x-8:.2f}" y="{y-4:.2f}" width="16" height="8" rx="3" fill="{fills[kind]}" stroke="{slate}" stroke-width="1.5"/>'
                   f'<circle cx="{tx:.2f}" cy="{ty:.2f}" r="2" fill="{slate}" opacity=".45"/></g>')
    out.append(f'<path d="M180 24C180 5 226 7 232 22M151 234C126 251 165 255 180 238" fill="none" stroke="{green}" stroke-width="2" stroke-linecap="round"/></svg>\n')
    return ''.join(out)


def outputs(profile):
    artifacts = {"editorial/tokens.css": tokens_css(profile),
                 "editorial/report-tokens.css": report_tokens_css(profile),
                 "editorial/signal-loom.svg": loom(profile)}
    receipt = {"schema": "warm-precision-editorial/1", "profile": profile["version"],
               "profile_sha256": hashlib.sha256(SOURCE.with_name("tokens.json").read_bytes()).hexdigest(),
               "loom_source_sha256": hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
               "artifacts": [{"file": k.removeprefix("editorial/"), "sha256": hashlib.sha256(v.encode()).hexdigest()} for k, v in artifacts.items()],
               "contrast": contrast_pairs(profile), "illustration_not_circuit_map": True}
    artifacts["editorial/receipt.json"] = json.dumps(receipt, indent=2) + '\n'
    return artifacts
